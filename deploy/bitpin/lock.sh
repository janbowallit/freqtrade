#!/usr/bin/env bash
# Pin the server image to the package versions of the Mac venv the bot is tested on.
# requirements.txt pins newer versions that break ccxt_bitpin (ccxt fetch2 signature).
# Writes deploy/bitpin/requirements.lock (direct deps) and constraints.txt (everything).
# Usage: deploy/bitpin/lock.sh   (re-run after upgrading the Mac venv)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

.venv/bin/python -m pip freeze --exclude-editable | grep -vE '^appnope==' > deploy/bitpin/constraints.txt

python3 - <<'EOF'
import re

norm = lambda n: re.sub(r"[-_.]+", "-", n).lower()
mac = {
    norm(line.split("==")[0]): line.strip()
    for line in open("deploy/bitpin/constraints.txt")
    if "==" in line
}
out = ["# Generated by deploy/bitpin/lock.sh from the Mac venv - do not edit."]
skipped = []
for line in open("requirements.txt"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    req, _, marker = line.partition(";")
    name = re.split(r"[=<>!~ ]", req)[0]
    pin = mac.get(norm(name))
    if not pin:
        skipped.append(name)
        continue
    out.append(pin + (";" + marker if marker else ""))
open("deploy/bitpin/requirements.lock", "w").write("\n".join(out) + "\n")
print("Not installed on the Mac, left out:", ", ".join(skipped) or "none")
EOF
